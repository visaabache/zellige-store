import type { NextConfig } from "next";
import path from "node:path";

const supabaseHost = (() => {
  try {
    return process.env.SUPABASE_URL ? new URL(process.env.SUPABASE_URL).hostname : null;
  } catch {
    return null;
  }
})();

const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
];

const config: NextConfig = {
  poweredByHeader: false,
  // This app lives in a sub-folder of a larger repository: trace files from here, not from the repo root.
  outputFileTracingRoot: path.join(__dirname),
  // Cloudflare Workers have no image optimizer: images are served as stored (catalog photos are pre-sized,
  // admin uploads are resized in the browser). On Node.js hosting, next/image optimises them.
  serverExternalPackages: ["@prisma/client", "bcryptjs", "sharp"],
  images: {
    unoptimized: process.env.CF_BUILD === "1",
    formats: ["image/avif", "image/webp"],
    deviceSizes: [360, 480, 640, 828, 1080, 1280, 1600, 1920],
    remotePatterns: supabaseHost ? [{ protocol: "https", hostname: supabaseHost, pathname: "/storage/v1/object/public/**" }] : [],
  },
  experimental: {
    serverActions: { bodySizeLimit: "25mb" },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default config;
