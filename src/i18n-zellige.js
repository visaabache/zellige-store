/** Merges the store wording into the engine dictionary (nested objects such as `js` are merged, not replaced). */
export function applyStoreWording(T) {
  for (const lang of Object.keys(Z)) {
    for (const [k, v] of Object.entries(Z[lang])) {
      if (v && typeof v === 'object' && !Array.isArray(v) && T[lang][k] && typeof T[lang][k] === 'object' && !Array.isArray(T[lang][k]) && k === 'js') Object.assign(T[lang][k], v);
      else T[lang][k] = v;
    }
  }
  return T;
}
